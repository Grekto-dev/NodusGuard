def tr(key: str, **kwargs: Any) -> str:
    """Traduz chave de UI para o idioma ativo com formatação opcional."""
    catalog = TRANSLATIONS.get(_current_language, TRANSLATIONS[DEFAULT_LANGUAGE])
    template = catalog.get(key)
    if template is None:
        template = TRANSLATIONS[DEFAULT_LANGUAGE].get(key, key)
    if kwargs:
        return template.format(**kwargs)
    return template
